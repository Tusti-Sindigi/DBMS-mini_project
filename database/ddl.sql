-- ============================================================================
-- Table: users
-- Description: Stores authenticated system users with role-based access control.
-- Roles: 'Client', 'Reviewer', 'LegalAdmin'
-- ============================================================================
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('Client', 'Reviewer', 'LegalAdmin')),
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE users IS 'User accounts with role-based access control (Client, Reviewer, LegalAdmin)';
COMMENT ON COLUMN users.id IS 'Primary key identity generated by PostgreSQL';
COMMENT ON COLUMN users.name IS 'Unique login username/identifier';
COMMENT ON COLUMN users.role IS 'Role of the user: Client, Reviewer, or LegalAdmin';
COMMENT ON COLUMN users.password_hash IS 'bcrypt-hashed password string';
COMMENT ON COLUMN users.created_at IS 'Timestamp when user account was registered';


-- ============================================================================
-- Table: contracts
-- Description: Stores metadata of uploaded contract documents and triage status.
-- Statuses: 'Processing', 'Analyzed', 'Failed'
-- ============================================================================
CREATE TABLE IF NOT EXISTS contracts (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    uploaded_by BIGINT NOT NULL REFERENCES users(id),
    client_id BIGINT NOT NULL REFERENCES users(id),
    file_name TEXT,
    upload_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status TEXT NOT NULL DEFAULT 'Processing'
        CHECK (status IN ('Processing', 'Analyzed', 'Failed'))
);

COMMENT ON TABLE contracts IS 'Uploaded contract documents associated with clients and uploaders';
COMMENT ON COLUMN contracts.id IS 'Primary key identity for contract record';
COMMENT ON COLUMN contracts.uploaded_by IS 'Foreign key referencing users(id) who uploaded the file';
COMMENT ON COLUMN contracts.client_id IS 'Foreign key referencing users(id) owning the contract';
COMMENT ON COLUMN contracts.file_name IS 'Original file name of the contract document';
COMMENT ON COLUMN contracts.upload_date IS 'Timestamp of contract upload';
COMMENT ON COLUMN contracts.status IS 'Current processing state: Processing, Analyzed, or Failed';


-- ============================================================================
-- Table: clauses
-- Description: Stores individual segmented clauses parsed from contracts along
--              with 384-dimensional dense vector embeddings.
-- ============================================================================
CREATE TABLE IF NOT EXISTS clauses (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    clause_text TEXT NOT NULL CHECK (BTRIM(clause_text) <> ''),
    clause_number TEXT NOT NULL,
    embedding VECTOR(384),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_clauses_contract_clause_number UNIQUE (contract_id, clause_number)
);

COMMENT ON TABLE clauses IS 'Segmented legal clauses extracted from contracts with vector embeddings';
COMMENT ON COLUMN clauses.id IS 'Primary key identity for clause record';
COMMENT ON COLUMN clauses.contract_id IS 'Foreign key referencing parent contract; cascades on contract deletion';
COMMENT ON COLUMN clauses.clause_text IS 'Exact textual content of the clause';
COMMENT ON COLUMN clauses.clause_number IS 'Section or clause index within contract (e.g., 1.0, 2.1)';
COMMENT ON COLUMN clauses.embedding IS '384-dimensional dense vector representation from sentence-transformers';
COMMENT ON COLUMN clauses.created_at IS 'Timestamp when clause was extracted and saved';


-- ============================================================================
-- Table: risk_library
-- Description: Curated reference catalog of predatory legal provisions and
--              patterns with assigned risk categories and severity weights (1-5).
-- ============================================================================
CREATE TABLE IF NOT EXISTS risk_library (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    clause_pattern_text TEXT NOT NULL UNIQUE CHECK (BTRIM(clause_pattern_text) <> ''),
    risk_category TEXT NOT NULL,
    severity_weight SMALLINT NOT NULL CHECK (severity_weight BETWEEN 1 AND 5),
    embedding VECTOR(384),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE risk_library IS 'Catalog of known high-risk predatory clause patterns';
COMMENT ON COLUMN risk_library.id IS 'Primary key identity for risk pattern';
COMMENT ON COLUMN risk_library.clause_pattern_text IS 'Sample reference clause text representing predatory term';
COMMENT ON COLUMN risk_library.risk_category IS 'Classification category (e.g. Unlimited Liability, Auto-Renewal Trap)';
COMMENT ON COLUMN risk_library.severity_weight IS 'Risk weight from 1 (lowest) to 5 (most severe)';
COMMENT ON COLUMN risk_library.embedding IS '384-dimensional dense vector for semantic similarity matching';
COMMENT ON COLUMN risk_library.created_at IS 'Timestamp when pattern was cataloged';


-- ============================================================================
-- Table: flags
-- Description: Flags generated when a contract clause semantically matches a
--              risk library pattern above the configured threshold.
-- Statuses: 'Open', 'Cleared', 'Escalated'
-- ============================================================================
CREATE TABLE IF NOT EXISTS flags (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    clause_id BIGINT NOT NULL REFERENCES clauses(id) ON DELETE CASCADE,
    risk_library_id BIGINT NOT NULL REFERENCES risk_library(id),
    similarity_score REAL NOT NULL CHECK (similarity_score BETWEEN -1 AND 1),
    status TEXT NOT NULL DEFAULT 'Open'
        CHECK (status IN ('Open', 'Cleared', 'Escalated')),
    reviewer_id BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE flags IS 'Risk flags matching clauses to risk patterns requiring reviewer triage';
COMMENT ON COLUMN flags.id IS 'Primary key identity for flag';
COMMENT ON COLUMN flags.clause_id IS 'Foreign key referencing flagged clause; cascades on clause deletion';
COMMENT ON COLUMN flags.risk_library_id IS 'Foreign key referencing matched risk library pattern';
COMMENT ON COLUMN flags.similarity_score IS 'Cosine similarity score between clause and pattern vector';
COMMENT ON COLUMN flags.status IS 'Current triage status: Open, Cleared, or Escalated';
COMMENT ON COLUMN flags.reviewer_id IS 'Foreign key referencing reviewer assigned to this flag';
COMMENT ON COLUMN flags.created_at IS 'Timestamp when flag was raised';


-- ============================================================================
-- Table: review_history
-- Description: Immutable audit trail logging every triage decision made by
--              legal reviewers on flagged clauses.
-- Actions: 'Cleared', 'Escalated'
-- ============================================================================
CREATE TABLE IF NOT EXISTS review_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    flag_id BIGINT NOT NULL REFERENCES flags(id) ON DELETE CASCADE,
    action TEXT NOT NULL CHECK (action IN ('Cleared', 'Escalated')),
    "timestamp" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewer_id BIGINT NOT NULL REFERENCES users(id)
);

COMMENT ON TABLE review_history IS 'Audit log of reviewer decisions on flags for accountability and tracking';
COMMENT ON COLUMN review_history.id IS 'Primary key identity for review history audit entry';
COMMENT ON COLUMN review_history.flag_id IS 'Foreign key referencing reviewed flag; cascades on flag deletion';
COMMENT ON COLUMN review_history.action IS 'Decision action taken: Cleared or Escalated';
COMMENT ON COLUMN review_history.timestamp IS 'Timestamp when review action was executed';
COMMENT ON COLUMN review_history.reviewer_id IS 'Foreign key referencing reviewer who performed the action';


-- ============================================================================
-- Table: risk_config
-- Description: Singleton configuration table storing the dynamic cosine
--              similarity threshold for automatic risk flag generation.
-- ============================================================================
CREATE TABLE IF NOT EXISTS risk_config (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    similarity_threshold REAL NOT NULL DEFAULT 0.75
        CHECK (similarity_threshold > 0 AND similarity_threshold <= 1)
);

COMMENT ON TABLE risk_config IS 'System-wide singleton configuration for similarity threshold';
COMMENT ON COLUMN risk_config.id IS 'Singleton primary key locked to 1';
COMMENT ON COLUMN risk_config.similarity_threshold IS 'Minimum cosine similarity score (0.0 to 1.0) to trigger flag';


