-- View: unresolved_flags_by_client
-- Description: CTE-backed view aggregating open flags, average similarity,
--              average risk score, and total contracts per client.
CREATE OR REPLACE VIEW unresolved_flags_by_client AS
WITH client_flags AS (
    -- CTE 1: aggregate open/unresolved flags and risk metrics per client
    SELECT
        c.client_id,
        COUNT(f.id)                                       AS open_flag_count,
        ROUND(AVG(f.similarity_score)::NUMERIC, 4)         AS avg_similarity_score,
        ROUND(
            AVG(
                GREATEST(f.similarity_score, 0)
                * rl.severity_weight / 5.0 * 100
            )::NUMERIC, 2
        )                                                 AS avg_risk_score,
        MAX(f.created_at)                                 AS latest_flag_date
    FROM flags f
    JOIN clauses cl      ON cl.id = f.clause_id
    JOIN contracts c     ON c.id = cl.contract_id
    JOIN risk_library rl ON rl.id = f.risk_library_id
    WHERE f.status = 'Open'
    GROUP BY c.client_id
),
client_contracts AS (
    -- CTE 2: aggregate total contracts per client
    SELECT
        client_id,
        COUNT(id) AS total_contracts
    FROM contracts
    GROUP BY client_id
)
SELECT
    u.id                                                    AS client_id,
    u.name                                                  AS client_name,
    COALESCE(cc.total_contracts, 0)                         AS total_contracts,
    COALESCE(cf.open_flag_count, 0)                          AS open_flag_count,
    cf.avg_similarity_score,
    cf.avg_risk_score,
    cf.latest_flag_date
FROM users u
LEFT JOIN client_contracts cc ON cc.client_id = u.id
LEFT JOIN client_flags cf     ON cf.client_id = u.id
WHERE u.role = 'Client';

COMMENT ON VIEW unresolved_flags_by_client IS 'Analytical CTE view aggregating open flags, average risk, and total contracts per client';


-- ============================================================================
-- Security View 1: client_contracts_view
-- Description: Restricts client contract access to non-sensitive columns
--              (omitting uploader IDs and internal account linkages).
-- ============================================================================
CREATE OR REPLACE VIEW client_contracts_view AS
SELECT 
    id, 
    file_name, 
    upload_date, 
    status, 
    client_id
FROM contracts;

COMMENT ON VIEW client_contracts_view IS 'Security view restricting client contract access to non-sensitive columns';


-- ============================================================================
-- Security View 2: reviewer_open_flags_view
-- Description: Pre-joined operational view providing reviewers with full
--              context to triage open flags without browsing raw tables.
-- ============================================================================
CREATE OR REPLACE VIEW reviewer_open_flags_view AS
SELECT 
    f.id AS flag_id,
    f.clause_id,
    cl.clause_number,
    cl.clause_text,
    c.file_name AS contract_file,
    rl.risk_category,
    rl.severity_weight,
    f.similarity_score,
    f.status,
    f.created_at
FROM flags f
JOIN clauses cl ON cl.id = f.clause_id
JOIN contracts c ON c.id = cl.contract_id
JOIN risk_library rl ON rl.id = f.risk_library_id
WHERE f.status = 'Open';

COMMENT ON VIEW reviewer_open_flags_view IS 'Role-based operational view showing only open flags requiring reviewer triage with joined context';


-- ============================================================================
-- Security View 3: admin_system_users_view
-- Description: Conceals password_hash column while exposing necessary account
--              profile details for administration.
-- ============================================================================
CREATE OR REPLACE VIEW admin_system_users_view AS
SELECT 
    id, 
    name, 
    role, 
    created_at
FROM users;

COMMENT ON VIEW admin_system_users_view IS 'Security view exposing user accounts while strictly concealing sensitive password_hash';


